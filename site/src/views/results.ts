import { getData, type MetricRow, type ResultsFile } from "../data";
import { MODEL_ORDER, modelColor } from "../models";
import { esc, pct } from "../util";

const TYPE_LABEL: Record<string, string> = {
  gap: "AIS gap",
  jump: "Impossible jump",
  loiter: "Loitering",
  deviation: "Route deviation",
  rendezvous: "Rendezvous",
};
const UNIT: Record<string, string> = { gap: "min", jump: "km", loiter: "h", deviation: "km", rendezvous: "h" };

function legend(ids: string[], label: (id: string) => string): string {
  return `<div class="legend" style="grid-auto-flow:column;grid-template-columns:none;justify-content:start;gap:0.4rem 1rem;flex-wrap:wrap;display:flex">
    ${ids.map((id) => `<span><i class="swatch" style="background:${modelColor(id)};height:4px"></i>${esc(label(id))}</span>`).join("")}</div>`;
}

function metricTable(rows: MetricRow[], label: (id: string) => string): string {
  return `<div class="table-wrap"><table>
    <thead><tr><th>Model</th><th class="num">Horizon</th><th class="num">Samples</th><th class="num">Mean error (km) [95% CI]</th>
    <th class="num">Median</th><th class="num">90th pct</th><th class="num">50% cover</th><th class="num">90% cover</th><th class="num">NLL</th></tr></thead>
    <tbody>${rows
      .map(
        (r) => `<tr><td>${esc(label(r.model))}</td><td class="num">${r.horizon_min} min</td><td class="num">${r.n.toLocaleString("en")}</td>
        <td class="num">${r.mean_km.toFixed(2)} [${r.mean_lo.toFixed(2)}, ${r.mean_hi.toFixed(2)}]</td><td class="num">${r.median_km.toFixed(2)}</td>
        <td class="num">${r.p90_km.toFixed(2)}</td><td class="num">${pct(r.cov50)}</td><td class="num">${pct(r.cov90)}</td><td class="num">${r.nll.toFixed(2)}</td></tr>`,
      )
      .join("")}</tbody></table></div>`;
}

export async function render(root: HTMLElement): Promise<void> {
  const r = await getData<ResultsFile>("results.json");
  const label = (id: string) => r.models.find((m) => m.id === id)?.label ?? id;
  const ids = MODEL_ORDER.filter((id) => r.prediction?.rows.some((x) => x.model === id));
  const rows = (r.prediction?.rows ?? []).filter((x) => ids.includes(x.model));
  const criteriaRows = r.criteria
    .map(
      (c) => `<tr><td>${esc(c.area)}</td><td>${esc(c.name)}</td><td>${esc(c.target)}</td><td>${esc(c.result)}</td>
      <td>${c.met ? '<span class="pill ok">✓ met</span>' : '<span class="pill bad">✗ not met</span>'}</td></tr>`,
    )
    .join("");

  root.innerHTML = `
  <div class="page">
    ${r.note ? `<div class="callout" role="note"><strong>Note:</strong> ${esc(r.note)}</div>` : ""}
    <h1>Results &amp; methods</h1>
    <p class="muted">All numbers are generated by the pipeline and copied here unedited. The
    prediction table is the <strong>${esc(r.prediction?.split ?? "–")}</strong> split. Targets were fixed in
    <a href="https://github.com/jrhughes003/ais-sentinel/blob/main/PLAN.md">PLAN.md</a> before any result was seen.</p>

    <h2 id="criteria">Success criteria</h2>
    <div class="table-wrap"><table><thead><tr><th>Area</th><th>Criterion</th><th>Target</th><th>Result</th><th>Status</th></tr></thead>
    <tbody>${criteriaRows}</tbody></table></div>

    <h2 id="prediction">Trajectory prediction</h2>
    <p>Mean great-circle error between predicted and true position, by horizon, with 95%
    confidence intervals from a <em>voyage-cluster bootstrap</em> (whole voyages are resampled,
    because ten forecasts from one straight run are not ten independent tests). Lower is better.</p>
    ${legend(ids, label)}
    <div class="chart" id="chart-error" role="img" aria-label="Mean prediction error in kilometres versus forecast horizon, one line per model, with 95% confidence intervals"></div>
    ${
      r.verdict.length
        ? `<h3>Best ML model vs the best baseline at each horizon</h3>
      <div class="table-wrap"><table><thead><tr><th class="num">Horizon</th><th>Best baseline</th><th class="num">Difference (km) [95% CI]</th><th class="num">Relative</th></tr></thead>
      <tbody>${r.verdict
        .map(
          (v) => `<tr><td class="num">${v.horizon} min</td><td>${esc(label(v.best_baseline))}</td>
          <td class="num">${v.diff_km >= 0 ? "+" : ""}${v.diff_km.toFixed(2)} [${v.lo.toFixed(2)}, ${v.hi.toFixed(2)}]</td>
          <td class="num">${v.rel >= 0 ? "+" : ""}${(100 * v.rel).toFixed(1)}%</td></tr>`,
        )
        .join("")}</tbody></table></div>
      <p class="small muted">Negative = the ML model is better. The CI excludes 0 when the difference is significant.</p>`
        : ""
    }
    <h3>Is the uncertainty honest?</h3>
    <p>Share of true positions inside each model's 90% ellipse (target band 85–95%, shaded).
    Calibration was fitted on the validation month only.</p>
    ${legend(ids, label)}
    <div class="chart" id="chart-cov" role="img" aria-label="Empirical coverage of 90 percent prediction ellipses by model and horizon"></div>
    <details><summary>Full prediction table</summary>${metricTable(rows, label)}</details>

    <h2 id="tracking">Tracking (simulation with known truth)</h2>
    <p>Real AIS has no ground truth, so filters are validated on simulated voyages with
    AIS-like reporting gaps, GPS noise and gross outliers. Errors in metres.</p>
    <div class="table-wrap"><table><thead><tr><th>Segment</th><th class="num">CV-KF RMSE</th><th class="num">IMM RMSE</th>
      <th class="num">CV / IMM median</th><th class="num">CV / IMM 95th pct</th></tr></thead><tbody>
      ${r.tracking
        .map(
          (t) => `<tr><td>${esc(t.segment)}</td><td class="num">${t.cv_rmse.toFixed(1)}</td><td class="num">${t.imm_rmse.toFixed(1)}</td>
          <td class="num">${t.cv_median.toFixed(1)} / ${t.imm_median.toFixed(1)}</td><td class="num">${t.cv_p95.toFixed(1)} / ${t.imm_p95.toFixed(1)}</td></tr>`,
        )
        .join("")}</tbody></table></div>
    <p class="small muted">RMSE is dominated by a handful of rare events (a fix rejected right after a
    reporting gap, or an outlier admitted during a manoeuvre); the median and 95th percentile show
    typical behaviour. See DECISIONS.md D15 and D19.</p>
    ${r.tracking_note ? `<div class="callout small" role="note">${esc(r.tracking_note)}</div>` : ""}

    <h2 id="anomaly">Anomaly detection (synthetic injection)</h2>
    <p>Anomalies with known ground truth were injected into real test-month voyages at a range of
    magnitudes. Recall: share of injected anomalies found. Precision: share of <em>new</em>
    alarms that were the injected anomaly.</p>
    <div class="chart" id="chart-anom" role="img" aria-label="Recall and precision of each anomaly detector versus anomaly magnitude"></div>
    <details><summary>Anomaly table</summary><div class="table-wrap"><table><thead><tr><th>Type</th><th class="num">Magnitude</th><th class="num">n</th><th class="num">Precision</th><th class="num">Recall</th></tr></thead>
    <tbody>${(r.anomaly?.by_magnitude ?? [])
      .map(
        (a) => `<tr><td>${esc(TYPE_LABEL[a.type] ?? a.type)}</td><td class="num">${a.magnitude} ${UNIT[a.type] ?? ""}</td><td class="num">${a.n}</td>
        <td class="num">${pct(a.precision)}</td><td class="num">${pct(a.recall)}</td></tr>`,
      )
      .join("")}</tbody></table></div></details>

    <h2 id="methods">Methods in brief</h2>
    <ul>
      <li><strong>Data.</strong> MarineCadastre.gov AIS (US Coast Guard receivers), ${esc(r.period.start)} – ${esc(r.period.end)},
      filtered to ${esc(r.region.name)}; ${r.counts.points.toLocaleString("en")} cleaned reports.</li>
      <li><strong>Splits.</strong> By time with one-day buffers; a voyage belongs to one split only.
      The October test month was evaluated once per model version and every run is logged.</li>
      <li><strong>Tracking.</strong> Constant-velocity Kalman filter and a 3-mode IMM (stationary,
      cruising, coordinated turn via EKF) with outlier rejection against a clutter model.</li>
      <li><strong>Baselines.</strong> Dead reckoning, Kalman and IMM extrapolation, and a "route
      analog" k-nearest-neighbour model using where training vessels went from the same place and heading.</li>
      <li><strong>ML.</strong> A GRU reads the last hour and predicts corrections to dead reckoning
      as a Gaussian (or 3-component mixture), trained by likelihood, ensembled over seeds.</li>
      <li><strong>Anomalies.</strong> Transparent rules with context learned from training data:
      receiver coverage, port/anchorage zones, lane density and usual headings.</li>
    </ul>

    <h2 id="limitations">Limitations</h2>
    <ul>
      <li>MarineCadastre keeps one report per vessel per minute; fast manoeuvres are undersampled.</li>
      <li>One region and one season; results may not transfer to open ocean or winter ice conditions.</li>
      <li>Synthetic anomalies measure detectability of the injected patterns, not of real deception,
      which is rarer and more varied.</li>
      <li>Canadian-side coverage depends on how far US receivers reach.</li>
      <li>MMSI is treated as identity; shared or spoofed identities appear only as kinematic symptoms.</li>
    </ul>
  </div>`;

  // Charts are optional enhancements; the tables carry the same numbers. Each chart's wrapper
  // has role="img" plus a description, so Plot's internal SVG is hidden from assistive tech.
  const Plot = await import("@observablehq/plot");
  const mount = (sel: string, el: Element): void => {
    el.setAttribute("aria-hidden", "true");
    root.querySelector(sel)?.append(el);
  };
  const ink = getComputedStyle(document.documentElement).getPropertyValue("--fg").trim() || "#16202c";
  const common = { style: { background: "transparent", color: ink, fontSize: "13px" }, marginLeft: 56 };
  const color = { domain: ids, range: ids.map(modelColor) };
  const H = [...new Set(rows.map((x) => x.horizon_min))].sort((a, b) => a - b);

  mount(
    "#chart-error",
    Plot.plot({
      ...common,
      width: Math.min(900, root.clientWidth - 32),
      height: 340,
      x: { label: "Forecast horizon (min)", ticks: H, grid: false },
      y: { label: "Mean error (km)", grid: true, zero: true },
      color,
      marks: [
        Plot.ruleY([0]),
        // CI bars, dodged a little per model so they do not overlap.
        Plot.ruleX(rows, { x: (d: MetricRow) => d.horizon_min + (ids.indexOf(d.model) - (ids.length - 1) / 2) * 1.2, y1: "mean_lo", y2: "mean_hi", stroke: "model", strokeWidth: 2 }),
        Plot.lineY(rows, { x: "horizon_min", y: "mean_km", stroke: "model", strokeWidth: 2 }),
        Plot.dot(rows, { x: "horizon_min", y: "mean_km", fill: "model", r: 4, stroke: "var(--bg)", strokeWidth: 2 }),
        Plot.tip(rows, Plot.pointer({ x: "horizon_min", y: "mean_km", title: (d: MetricRow) => `${label(d.model)}\n${d.horizon_min} min: ${d.mean_km.toFixed(2)} km [${d.mean_lo.toFixed(2)}, ${d.mean_hi.toFixed(2)}]` })),
      ],
    }),
  );

  mount(
    "#chart-cov",
    Plot.plot({
      ...common,
      width: Math.min(900, root.clientWidth - 32),
      height: 260,
      x: { label: "Forecast horizon (min)", ticks: H },
      y: { label: "90% ellipse coverage", domain: [0.5, 1], tickFormat: "%", grid: true },
      color,
      marks: [
        Plot.rectY([0], { x1: Math.min(...H) - 5, x2: Math.max(...H) + 5, y1: 0.85, y2: 0.95, fill: "var(--ok)", fillOpacity: 0.12 }),
        Plot.ruleY([0.9], { stroke: "var(--ok)", strokeDasharray: "4 3" }),
        Plot.lineY(rows, { x: "horizon_min", y: "cov90", stroke: "model", strokeWidth: 2 }),
        Plot.dot(rows, { x: "horizon_min", y: "cov90", fill: "model", r: 4, stroke: "var(--bg)", strokeWidth: 2 }),
        Plot.tip(rows, Plot.pointer({ x: "horizon_min", y: "cov90", title: (d: MetricRow) => `${label(d.model)}\n${d.horizon_min} min: ${pct(d.cov90)} inside 90% ellipse` })),
      ],
    }),
  );

  const am = (r.anomaly?.by_magnitude ?? []).flatMap((a) => [
    { ...a, metric: "recall", value: a.recall },
    { ...a, metric: "precision", value: a.precision },
  ]);
  if (am.length) {
    mount(
      "#chart-anom",
      Plot.plot({
        ...common,
        width: Math.min(1000, root.clientWidth - 32),
        height: 260,
        fx: { label: null, tickFormat: (t: string) => TYPE_LABEL[t] ?? t, padding: 0.12 },
        x: { label: "Anomaly magnitude (min / km / h; see table)", type: "point", tickRotate: 0 },
        y: { label: "Rate", domain: [0, 1], tickFormat: "%", grid: true },
        color: { domain: ["recall", "precision"], range: [modelColor("dead_reckoning"), modelColor("kf_cv")], legend: true },
        marks: [
          Plot.lineY(am, { fx: "type", x: (d: { magnitude: number }) => String(d.magnitude), y: "value", stroke: "metric", strokeWidth: 2 }),
          Plot.dot(am, { fx: "type", x: (d: { magnitude: number }) => String(d.magnitude), y: "value", fill: "metric", r: 3.5 }),
          Plot.tip(am, Plot.pointer({ fx: "type", x: (d: { magnitude: number }) => String(d.magnitude), y: "value", title: (d: { type: string; magnitude: number; metric: string; value: number; n: number }) => `${TYPE_LABEL[d.type]} @ ${d.magnitude} ${UNIT[d.type]}\n${d.metric}: ${pct(d.value)} (n=${d.n})` })),
        ],
      }),
    );
  }
}
